import { describe, expect, it } from "vitest";

import { lunarNewYear } from "./lunar-new-year";

describe("lunarNewYear", () => {
  it.each([
    // China kept summer time in the 1940s; the calendar never did.
    [1944, "1944-01-25"],
    [1950, "1950-02-17"],
    [1961, "1961-02-15"],
    [1966, "1966-01-21"],
    [1980, "1980-02-16"],
    [1984, "1984-02-02"],
    // The solstice and the new moon fall on the same Beijing day.
    [1985, "1985-02-20"],
    [1987, "1987-01-29"],
    [1988, "1988-02-17"],
    [1989, "1989-02-06"],
    [1990, "1990-01-27"],
    [1995, "1995-01-31"],
    [2000, "2000-02-05"],
    [2001, "2001-01-24"],
    [2005, "2005-02-09"],
    [2010, "2010-02-14"],
    [2015, "2015-02-19"],
    [2019, "2019-02-05"],
    [2020, "2020-01-25"],
    [2021, "2021-02-12"],
    [2022, "2022-02-01"],
    [2023, "2023-01-22"],
    [2024, "2024-02-10"],
    [2025, "2025-01-29"],
    [2026, "2026-02-17"],
    [2027, "2027-02-06"],
    [2028, "2028-01-26"],
    [2030, "2030-02-03"],
    [2033, "2033-01-31"],
    // A leap month after the solstice of 2033 puts it a month on.
    [2034, "2034-02-19"],
  ])("falls in %i on %s", (year, day) => {
    expect(lunarNewYear(year)).toBe(day);
  });
});
